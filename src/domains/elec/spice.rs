use crate::core::ir::{CanonicalIr, EntityGeometryIr, PortRole};
use crate::core::units::VoltageSpec;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BranchSimResult {
    pub component: String,
    pub category: String,
    pub value: String,
    pub net_a: String,
    pub net_b: String,
    pub v_drop_v: f64,
    pub current_ma: f64,
    pub power_mw: f64,
    pub state: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RcFilterResult {
    pub node: String,
    pub resistor: String,
    pub r_ohm: f64,
    pub capacitor: String,
    pub c_farad: f64,
    pub cutoff_hz: f64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SimulationReport {
    pub project: String,
    pub method: String,
    pub converged: bool,
    pub iterations: usize,
    pub node_voltages_v: BTreeMap<String, f64>,
    pub branches: Vec<BranchSimResult>,
    pub rc_filters: Vec<RcFilterResult>,
}

/// Parse an EDL component value string (e.g. `"470ohm"`, `"10kohm"`, `"100nF"`, `"10uF"`, `"10uH"`, `"4.7k"`)
/// into its canonical SI floating-point value (Ohms, Farads, or Henrys).
pub fn parse_si_component_value(raw: &str, expected_kind: &str) -> Option<f64> {
    let s = raw.trim();
    if s.is_empty() {
        return None;
    }
    let mut num_end = 0usize;
    let bytes = s.as_bytes();
    while num_end < bytes.len()
        && (bytes[num_end].is_ascii_digit()
            || bytes[num_end] == b'.'
            || (num_end == 0 && bytes[num_end] == b'-'))
    {
        num_end += 1;
    }
    if num_end == 0 {
        return None;
    }
    let val: f64 = s[..num_end].parse().ok()?;
    let suffix = s[num_end..].trim();
    let mult = match (expected_kind, suffix) {
        ("R", "" | "ohm" | "Ohm" | "R" | "Ω") => 1.0,
        ("R", "k" | "K" | "kohm" | "kOhm" | "kΩ") => 1e3,
        ("R", "M" | "Mohm" | "MOhm" | "MΩ") => 1e6,
        ("R", "m" | "mohm" | "mOhm") => 1e-3,
        ("C", "F") => 1.0,
        ("C", "mF") => 1e-3,
        ("C", "uF" | "µF") => 1e-6,
        ("C", "nF") => 1e-9,
        ("C", "pF") => 1e-12,
        ("L", "H") => 1.0,
        ("L", "mH") => 1e-3,
        ("L", "uH" | "µH") => 1e-6,
        ("L", "nH") => 1e-9,
        _ => return None,
    };
    Some(val * mult)
}

fn led_forward_voltage(value: &str, is_led: bool) -> f64 {
    if !is_led {
        return 0.7;
    }
    let low = value.to_lowercase();
    if low.contains("blue") || low.contains("white") || low.contains("uv") {
        3.0
    } else if low.contains("green") {
        2.1
    } else if low.contains("yellow") || low.contains("amber") {
        2.0
    } else if low.contains("red") {
        1.9
    } else {
        2.0
    }
}

/// Export a standards-compliant SPICE3 / ngspice `.cir` netlist directly from Canonical IR.
pub fn export_spice_netlist(ir: &CanonicalIr) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "* EDL SPICE3 Netlist — {}", ir.project.name);
    let _ = writeln!(out, "* Generated by EDL v0.6.0 (compatible with ngspice / LTspice)");
    let _ = writeln!(out);

    let pin_net = build_pin_to_net_map(ir);
    let gnd_nets = collect_ground_nets(ir);
    let spice_node = |net: &str| -> String {
        if gnd_nets.contains(net) {
            "0".to_string()
        } else {
            net.replace(|c: char| !c.is_ascii_alphanumeric() && c != '_', "_")
        }
    };

    // 1. Ideal DC voltage sources for every directly driven `power_out (V)` rail (and fixed output pins!)
    let mut emitted_sources: BTreeSet<String> = BTreeSet::new();
    for ent in &ir.entities {
        let EntityGeometryIr::Component { pins, .. } = &ent.geometry else {
            continue;
        };
        for p in pins {
            if matches!(p.role, PortRole::PowerOut) {
                if let Some(VoltageSpec::Exact { volts }) = p.voltage {
                    if let Some(net) = pin_net.get(&(ent.id.clone(), p.name.clone())) {
                        if !gnd_nets.contains(net) && emitted_sources.insert(net.clone()) {
                            let _ = writeln!(
                                out,
                                "V_{}_{} {} 0 DC {:.4}",
                                sanitize_spice(&ent.id),
                                sanitize_spice(&p.name),
                                spice_node(net),
                                volts
                            );
                        }
                    }
                }
            }
        }
    }

    // 2. Passive, semiconductor, and op-amp elements
    let mut need_d_si = false;
    let mut need_d_led = false;

    for ent in &ir.entities {
        let EntityGeometryIr::Component {
            category,
            value,
            pins,
            ..
        } = &ent.geometry
        else {
            continue;
        };
        let cat = category.to_lowercase();
        let net_of = |p_name: &str| -> Option<String> {
            pin_net
                .get(&(ent.id.clone(), p_name.to_string()))
                .map(|n| spice_node(n))
        };

        match cat.as_str() {
            "resistor" | "r" if pins.len() >= 2 => {
                if let (Some(n1), Some(n2)) = (net_of(&pins[0].name), net_of(&pins[1].name)) {
                    let r = parse_si_component_value(value, "R").unwrap_or(1000.0);
                    let _ = writeln!(out, "R_{} {n1} {n2} {}", sanitize_spice(&ent.id), r);
                }
            }
            "capacitor" | "c" if pins.len() >= 2 => {
                if let (Some(n1), Some(n2)) = (net_of(&pins[0].name), net_of(&pins[1].name)) {
                    let c = parse_si_component_value(value, "C").unwrap_or(100e-9);
                    let _ = writeln!(out, "C_{} {n1} {n2} {:.6e}", sanitize_spice(&ent.id), c);
                }
            }
            "inductor" | "l" | "ferrite" if pins.len() >= 2 => {
                if let (Some(n1), Some(n2)) = (net_of(&pins[0].name), net_of(&pins[1].name)) {
                    let l = parse_si_component_value(value, "L").unwrap_or(1e-6);
                    let _ = writeln!(out, "L_{} {n1} {n2} {:.6e}", sanitize_spice(&ent.id), l);
                }
            }
            "diode" | "d" | "led" | "zener" | "schottky" if pins.len() >= 2 => {
                let (a_pin, k_pin) = find_anode_cathode(pins);
                if let (Some(na), Some(nk)) = (net_of(&a_pin.name), net_of(&k_pin.name)) {
                    let is_led = cat == "led";
                    let model = if is_led {
                        need_d_led = true;
                        "D_LED"
                    } else {
                        need_d_si = true;
                        "D_SI"
                    };
                    let _ = writeln!(out, "D_{} {na} {nk} {model}", sanitize_spice(&ent.id));
                }
            }
            "opamp" | "op_amp" | "comparator" => {
                let inp = pins.iter().find(|p| {
                    let u = p.name.to_uppercase();
                    u.contains("INP") || u.contains("POS") || u.contains('+')
                });
                let inn = pins.iter().find(|p| {
                    let u = p.name.to_uppercase();
                    u.contains("INN") || u.contains("NEG") || u.contains('-')
                });
                let outp = pins.iter().find(|p| p.role == PortRole::Output || p.name.to_uppercase().contains("OUT"));
                if let (Some(p), Some(n), Some(o)) = (inp, inn, outp) {
                    if let (Some(np), Some(nn), Some(no)) = (net_of(&p.name), net_of(&n.name), net_of(&o.name)) {
                        let _ = writeln!(out, "E_{} {no} 0 {np} {nn} 1e5", sanitize_spice(&ent.id));
                    }
                }
            }
            _ => {}
        }
    }

    let _ = writeln!(out);
    if need_d_si {
        let _ = writeln!(out, ".model D_SI D(IS=1e-14 N=1.0 RS=1)");
    }
    if need_d_led {
        let _ = writeln!(out, ".model D_LED D(IS=1e-22 N=2.0 RS=15)");
    }
    let _ = writeln!(out, ".op");
    let _ = writeln!(out, ".end");
    out
}

/// Built-in exact Modified Nodal Analysis (MNA) DC operating-point + analytical RC filter simulator.
/// Zero external binaries required: solves exact node voltages, LED/resistor/inductor currents (mA),
/// power dissipation (mW), and RC low-pass `-3dB` cutoff frequencies (Hz).
pub fn simulate_dc_and_rc(ir: &CanonicalIr) -> SimulationReport {
    let pin_net = build_pin_to_net_map(ir);
    let gnd_nets = collect_ground_nets(ir);

    // Map every non-ground net to a sequential MNA node index (0..num_nodes)
    let mut net_to_idx: BTreeMap<String, usize> = BTreeMap::new();
    let mut idx_to_net: Vec<String> = Vec::new();
    for rel in &ir.relations {
        if !gnd_nets.contains(&rel.id) && !net_to_idx.contains_key(&rel.id) {
            let idx = idx_to_net.len();
            net_to_idx.insert(rel.id.clone(), idx);
            idx_to_net.push(rel.id.clone());
        }
    }
    let num_nodes = idx_to_net.len();

    // Collect ideal voltage sources: (net_idx, voltage_v)
    // Includes `power_out (Exact V)` AND driven digital `output (Exact V)` (e.g. MCU GPIO driving an LED!)
    let mut v_sources: Vec<(usize, f64)> = Vec::new();
    let mut driven_nodes: BTreeSet<usize> = BTreeSet::new();
    for ent in &ir.entities {
        let EntityGeometryIr::Component { pins, .. } = &ent.geometry else {
            continue;
        };
        for p in pins {
            if matches!(p.role, PortRole::PowerOut | PortRole::Output) {
                if let Some(VoltageSpec::Exact { volts }) = p.voltage {
                    if let Some(net) = pin_net.get(&(ent.id.clone(), p.name.clone())) {
                        if let Some(&n_idx) = net_to_idx.get(net) {
                            if driven_nodes.insert(n_idx) {
                                v_sources.push((n_idx, volts));
                            }
                        }
                    }
                }
            }
        }
    }

    // Collect passive 2-terminal resistors/inductors, diodes/LEDs, and op-amp VCVS
    struct RBranch {
        comp: String,
        cat: String,
        val: String,
        net_a: String,
        net_b: String,
        na: Option<usize>,
        nb: Option<usize>,
        r_ohm: f64,
    }
    struct DBranch {
        comp: String,
        cat: String,
        val: String,
        net_a: String,
        net_b: String,
        na: Option<usize>,
        nk: Option<usize>,
        vf: f64,
        r_on: f64,
        conducting: bool,
    }
    struct OpAmpBranch {
        np: Option<usize>,
        nn: Option<usize>,
        no: Option<usize>,
    }

    let mut r_branches: Vec<RBranch> = Vec::new();
    let mut d_branches: Vec<DBranch> = Vec::new();
    let mut opamps: Vec<OpAmpBranch> = Vec::new();

    for ent in &ir.entities {
        let EntityGeometryIr::Component {
            category,
            value,
            pins,
            ..
        } = &ent.geometry
        else {
            continue;
        };
        let cat = category.to_lowercase();
        let node_opt = |pname: &str| -> Option<(String, Option<usize>)> {
            let net = pin_net.get(&(ent.id.clone(), pname.to_string()))?;
            let idx = net_to_idx.get(net).copied();
            Some((net.clone(), idx))
        };

        match cat.as_str() {
            "resistor" | "r" if pins.len() >= 2 => {
                if let (Some((net_a, na)), Some((net_b, nb))) =
                    (node_opt(&pins[0].name), node_opt(&pins[1].name))
                {
                    let r_ohm = parse_si_component_value(value, "R").unwrap_or(1000.0).max(1e-3);
                    r_branches.push(RBranch {
                        comp: ent.id.clone(),
                        cat: category.clone(),
                        val: value.clone(),
                        net_a,
                        net_b,
                        na,
                        nb,
                        r_ohm,
                    });
                }
            }
            "inductor" | "l" | "ferrite" | "fuse" if pins.len() >= 2 => {
                if let (Some((net_a, na)), Some((net_b, nb))) =
                    (node_opt(&pins[0].name), node_opt(&pins[1].name))
                {
                    // Realistic low DC resistance (0.05 ohm) for ferrite beads / inductors / fuses at DC
                    r_branches.push(RBranch {
                        comp: ent.id.clone(),
                        cat: category.clone(),
                        val: value.clone(),
                        net_a,
                        net_b,
                        na,
                        nb,
                        r_ohm: 0.05,
                    });
                }
            }
            "diode" | "d" | "led" | "zener" | "schottky" if pins.len() >= 2 => {
                let (a_pin, k_pin) = find_anode_cathode(pins);
                if let (Some((net_a, na)), Some((net_b, nk))) =
                    (node_opt(&a_pin.name), node_opt(&k_pin.name))
                {
                    let is_led = cat == "led";
                    let vf = led_forward_voltage(value, is_led);
                    let r_on = if is_led { 15.0 } else { 1.0 };
                    d_branches.push(DBranch {
                        comp: ent.id.clone(),
                        cat: category.clone(),
                        val: value.clone(),
                        net_a,
                        net_b,
                        na,
                        nk,
                        vf,
                        r_on,
                        conducting: is_led, // initial guess: LEDs ON, shunt TVS diodes OFF
                    });
                }
            }
            "opamp" | "op_amp" | "comparator" => {
                let inp = pins.iter().find(|p| {
                    let u = p.name.to_uppercase();
                    u.contains("INP") || u.contains("POS") || u.contains('+')
                });
                let inn = pins.iter().find(|p| {
                    let u = p.name.to_uppercase();
                    u.contains("INN") || u.contains("NEG") || u.contains('-')
                });
                let outp = pins.iter().find(|p| {
                    p.role == PortRole::Output || p.name.to_uppercase().contains("OUT")
                });
                if let (Some(p), Some(n), Some(o)) = (inp, inn, outp) {
                    if let (Some((_, np)), Some((_, nn)), Some((_, no))) =
                        (node_opt(&p.name), node_opt(&n.name), node_opt(&o.name))
                    {
                        if let Some(o_idx) = no {
                            if !driven_nodes.contains(&o_idx) {
                                opamps.push(OpAmpBranch { np, nn, no });
                            }
                        }
                    }
                }
            }
            _ => {}
        }
    }

    // Iterative PWL MNA solve (converges in 1-4 iterations for arbitrary diode/LED networks)
    let mut node_v = vec![0.0_f64; num_nodes];
    let mut converged = false;
    let mut iterations = 0usize;

    for iter in 0..8 {
        iterations = iter + 1;
        let num_vs = v_sources.len() + opamps.len();
        let dim = num_nodes + num_vs;
        if dim == 0 {
            converged = true;
            break;
        }
        let mut mat = vec![vec![0.0_f64; dim]; dim];
        let mut rhs = vec![0.0_f64; dim];

        // Tiny GMIN shunt (1e-12 S) to ground keeps floating digital/capacitive nodes non-singular!
        for i in 0..num_nodes {
            mat[i][i] += 1e-12;
        }

        // Stamp resistors & DC inductors
        for rb in &r_branches {
            let g = 1.0 / rb.r_ohm;
            stamp_conductance(&mut mat, rb.na, rb.nb, g);
        }

        // Stamp diodes / LEDs using current PWL state
        for db in &d_branches {
            if db.conducting {
                // Conducting: series Vf + r_on -> Norton equivalent: conductance G=1/r_on, current source I=Vf/r_on from A->K
                let g = 1.0 / db.r_on;
                let i_eq = db.vf / db.r_on;
                stamp_conductance(&mut mat, db.na, db.nk, g);
                if let Some(a) = db.na {
                    rhs[a] += i_eq;
                }
                if let Some(k) = db.nk {
                    rhs[k] -= i_eq;
                }
            } else {
                // Reverse-biased / cutoff: tiny leakage conductance 1e-9 S
                stamp_conductance(&mut mat, db.na, db.nk, 1e-9);
            }
        }

        // Stamp ideal voltage sources (node_v[n] = V)
        for (k, &(n_idx, volts)) in v_sources.iter().enumerate() {
            let row = num_nodes + k;
            mat[n_idx][row] += 1.0;
            mat[row][n_idx] += 1.0;
            rhs[row] = volts;
        }

        // Stamp ideal op-amp VCVS: V(no) - A_ol * (V(np) - V(nn)) = 0
        let a_ol = 1e5;
        for (k, oa) in opamps.iter().enumerate() {
            let row = num_nodes + v_sources.len() + k;
            if let Some(o) = oa.no {
                mat[o][row] += 1.0;
                mat[row][o] += 1.0;
            }
            if let Some(p) = oa.np {
                mat[row][p] -= a_ol;
            }
            if let Some(n) = oa.nn {
                mat[row][n] += a_ol;
            }
        }

        if let Some(sol) = solve_linear_system(mat, rhs) {
            node_v = sol[..num_nodes].to_vec();
        } else {
            break;
        }

        // Update diode PWL conduction states and check convergence
        let mut changed = false;
        for db in &mut d_branches {
            let va = db.na.map(|i| node_v[i]).unwrap_or(0.0);
            let vk = db.nk.map(|i| node_v[i]).unwrap_or(0.0);
            let vd = va - vk;
            let should_conduct = vd > db.vf - 1e-4;
            if should_conduct != db.conducting {
                db.conducting = should_conduct;
                changed = true;
            }
        }
        if !changed {
            converged = true;
            break;
        }
    }

    // Build readable voltage map (including GND = 0.0V)
    let mut node_voltages_v = BTreeMap::new();
    for g in &gnd_nets {
        node_voltages_v.insert(g.clone(), 0.0);
    }
    for (idx, name) in idx_to_net.iter().enumerate() {
        node_voltages_v.insert(name.clone(), round4(node_v[idx]));
    }

    // Compute branch currents & power dissipation
    let mut branches = Vec::new();
    for rb in &r_branches {
        let va = rb.na.map(|i| node_v[i]).unwrap_or(0.0);
        let vb = rb.nb.map(|i| node_v[i]).unwrap_or(0.0);
        let v_drop = va - vb;
        let i_a = v_drop / rb.r_ohm;
        let p_w = v_drop * i_a;
        branches.push(BranchSimResult {
            component: rb.comp.clone(),
            category: rb.cat.clone(),
            value: rb.val.clone(),
            net_a: rb.net_a.clone(),
            net_b: rb.net_b.clone(),
            v_drop_v: round4(v_drop),
            current_ma: round4(i_a * 1000.0),
            power_mw: round4(p_w * 1000.0),
            state: "linear".to_string(),
        });
    }
    for db in &d_branches {
        let va = db.na.map(|i| node_v[i]).unwrap_or(0.0);
        let vk = db.nk.map(|i| node_v[i]).unwrap_or(0.0);
        let v_drop = va - vk;
        let i_a = if db.conducting {
            ((v_drop - db.vf) / db.r_on).max(0.0)
        } else {
            v_drop * 1e-9
        };
        let p_w = (v_drop * i_a).max(0.0);
        branches.push(BranchSimResult {
            component: db.comp.clone(),
            category: db.cat.clone(),
            value: db.val.clone(),
            net_a: db.net_a.clone(),
            net_b: db.net_b.clone(),
            v_drop_v: round4(v_drop),
            current_ma: round4(i_a * 1000.0),
            power_mw: round4(p_w * 1000.0),
            state: if db.conducting {
                "forward_biased".to_string()
            } else {
                "reverse_biased".to_string()
            },
        });
    }

    // Analytical RC low-pass filter cutoff detection: any non-GND net touching a resistor and a cap-to-GND
    let mut rc_filters = Vec::new();
    let mut caps_to_gnd: Vec<(String, String, f64)> = Vec::new(); // (node, comp_id, c_farad)
    for ent in &ir.entities {
        let EntityGeometryIr::Component {
            category,
            value,
            pins,
            ..
        } = &ent.geometry
        else {
            continue;
        };
        if matches!(category.to_lowercase().as_str(), "capacitor" | "c") && pins.len() >= 2 {
            if let (Some(n0), Some(n1)) = (
                pin_net.get(&(ent.id.clone(), pins[0].name.clone())),
                pin_net.get(&(ent.id.clone(), pins[1].name.clone())),
            ) {
                if let Some(c_val) = parse_si_component_value(value, "C") {
                    if gnd_nets.contains(n1) && !gnd_nets.contains(n0) {
                        caps_to_gnd.push((n0.clone(), ent.id.clone(), c_val));
                    } else if gnd_nets.contains(n0) && !gnd_nets.contains(n1) {
                        caps_to_gnd.push((n1.clone(), ent.id.clone(), c_val));
                    }
                }
            }
        }
    }
    for (node, cap_id, c_f) in &caps_to_gnd {
        // Skip power rails (decoupling caps aren't signal RC filters)
        let is_power_rail = ir
            .relations
            .iter()
            .find(|r| r.id == *node)
            .and_then(|r| r.driven_voltage_v)
            .is_some();
        if is_power_rail {
            continue;
        }
        for rb in &r_branches {
            if matches!(rb.cat.to_lowercase().as_str(), "resistor" | "r")
                && (&rb.net_a == node || &rb.net_b == node)
            {
                let fc = 1.0 / (2.0 * std::f64::consts::PI * rb.r_ohm * c_f);
                rc_filters.push(RcFilterResult {
                    node: node.clone(),
                    resistor: rb.comp.clone(),
                    r_ohm: round4(rb.r_ohm),
                    capacitor: cap_id.clone(),
                    c_farad: *c_f,
                    cutoff_hz: round4(fc),
                });
            }
        }
    }

    SimulationReport {
        project: ir.project.name.clone(),
        method: "exact_mna_dc_pwl_and_rc_ac_v0.6".to_string(),
        converged,
        iterations,
        node_voltages_v,
        branches,
        rc_filters,
    }
}

fn stamp_conductance(mat: &mut [Vec<f64>], na: Option<usize>, nb: Option<usize>, g: f64) {
    if let Some(a) = na {
        mat[a][a] += g;
    }
    if let Some(b) = nb {
        mat[b][b] += g;
    }
    if let (Some(a), Some(b)) = (na, nb) {
        mat[a][b] -= g;
        mat[b][a] -= g;
    }
}

/// Gaussian elimination with partial pivoting for exact MNA linear solve.
fn solve_linear_system(mut a: Vec<Vec<f64>>, mut b: Vec<f64>) -> Option<Vec<f64>> {
    let n = b.len();
    for col in 0..n {
        let mut pivot = col;
        let mut max_val = a[col][col].abs();
        for row in (col + 1)..n {
            let v = a[row][col].abs();
            if v > max_val {
                max_val = v;
                pivot = row;
            }
        }
        if max_val < 1e-18 {
            return None;
        }
        if pivot != col {
            a.swap(col, pivot);
            b.swap(col, pivot);
        }
        let diag = a[col][col];
        for row in (col + 1)..n {
            let factor = a[row][col] / diag;
            if factor.abs() < 1e-24 {
                continue;
            }
            for c in col..n {
                a[row][c] -= factor * a[col][c];
            }
            b[row] -= factor * b[col];
        }
    }
    let mut x = vec![0.0_f64; n];
    for row in (0..n).rev() {
        let mut sum = b[row];
        for c in (row + 1)..n {
            sum -= a[row][c] * x[c];
        }
        x[row] = sum / a[row][row];
    }
    Some(x)
}

fn build_pin_to_net_map(ir: &CanonicalIr) -> BTreeMap<(String, String), String> {
    let mut map = BTreeMap::new();
    for rel in &ir.relations {
        for cp in &rel.connects {
            if let Some((c, p)) = cp.split_once('.') {
                map.insert((c.to_string(), p.to_string()), rel.id.clone());
            }
        }
    }
    map
}

fn collect_ground_nets(ir: &CanonicalIr) -> BTreeSet<String> {
    ir.relations
        .iter()
        .filter(|r| r.is_ground)
        .map(|r| r.id.clone())
        .collect()
}

fn find_anode_cathode<'a>(
    pins: &'a [crate::core::ir::PlacedPinIr],
) -> (&'a crate::core::ir::PlacedPinIr, &'a crate::core::ir::PlacedPinIr) {
    let explicit_a = pins
        .iter()
        .find(|p| p.name.eq_ignore_ascii_case("A") || p.name.eq_ignore_ascii_case("ANODE"));
    let explicit_k = pins
        .iter()
        .find(|p| p.name.eq_ignore_ascii_case("K") || p.name.eq_ignore_ascii_case("CATHODE"));
    let a = explicit_a.unwrap_or(&pins[0]);
    let k = explicit_k.unwrap_or_else(|| {
        pins.iter()
            .find(|p| p.number != a.number)
            .unwrap_or(&pins[1])
    });
    (a, k)
}

fn sanitize_spice(s: &str) -> String {
    s.replace(|c: char| !c.is_ascii_alphanumeric() && c != '_', "_")
}

fn round4(v: f64) -> f64 {
    (v * 10_000.0).round() / 10_000.0
}
